import pytest

from minion import profiles
from minion.errors import MinionError, NotFound


def test_builtins_load_and_inherit():
    reg = profiles.load_all()
    for name in ("base", "browser", "office", "dev", "research", "data", "windows"):
        assert name in reg
        assert reg[name].builtin
    office = reg["office"]
    assert [p.name for p in office.chain()] == ["base", "browser", "office"]
    apps = [a.name for a in office.merged("apps")]
    assert "Firefox" in apps and "Writer" in apps and "Terminal" in apps
    assert office.merged("env")["MINION_BROWSER"] == "firefox-esr"
    assert reg["dev"].merged("apps")[0].command == "lxterminal"  # dev overrides the terminal


def test_dockerfile_generation():
    p = profiles.get("research")
    df = p.dockerfile("example/minion-browser:1")
    assert df.startswith("# Generated by Minion")
    assert "FROM example/minion-browser:1" in df
    assert "poppler-utils" in df and df.rstrip().endswith("USER agent")
    assert f'dev.minion.fingerprint="{p.fingerprint()}"' in df


def test_fingerprint_changes_with_packages():
    a = profiles.get("research")
    before = a.fingerprint()
    a.packages.append("cowsay")
    assert a.fingerprint() != before


def test_custom_profile(tmp_path, monkeypatch):
    home = tmp_path / "h"
    (home / "profiles").mkdir(parents=True)
    (home / "profiles" / "designer.toml").write_text(
        'extends = "browser"\ndescription = "GIMP"\npackages = ["gimp"]\napps = [{ name = "GIMP", command = "gimp" }]\n'
    )
    monkeypatch.setenv("MINION_HOME", str(home))
    p = profiles.get("designer")
    assert not p.builtin and p.extends == "browser"
    assert p.image == "minion-custom-designer:latest"
    assert "GIMP" in [a.name for a in p.merged("apps")]
    assert "designer" in profiles.names()


def test_invalid_profiles(tmp_path, monkeypatch):
    home = tmp_path / "h"
    (home / "profiles").mkdir(parents=True)
    monkeypatch.setenv("MINION_HOME", str(home))
    (home / "profiles" / "bad.toml").write_text("nope = 1\n")
    with pytest.raises(MinionError, match="unknown keys"):
        profiles.load_all()
    (home / "profiles" / "bad.toml").write_text('extends = "missing"\n')
    with pytest.raises(NotFound):
        profiles.get("bad").chain()


def test_unknown_profile():
    with pytest.raises(NotFound, match="Available"):
        profiles.get("does-not-exist")
