"""Desktop profiles: small TOML recipes that describe a desktop (apps, packages, tuning).

Built-in profiles live next to this file. Your own go in ~/.config/minion/profiles/
(or $MINION_HOME/profiles) and can extend any other profile:

    name = "designer"
    extends = "browser"
    description = "Firefox plus GIMP and Inkscape."
    packages = ["gimp", "inkscape"]
    apps = [{ name = "GIMP", command = "gimp" }, { name = "Inkscape", command = "inkscape" }]
"""

from __future__ import annotations

import hashlib
import json
import re
import tomllib
from dataclasses import dataclass, field
from pathlib import Path

from .. import config
from ..errors import MinionError, NotFound

BUILTIN_DIR = Path(__file__).parent
NAME_RE = re.compile(r"^[a-z0-9][a-z0-9_-]{0,30}$")
BUILTIN_ORDER = ["base", "browser", "office", "dev", "research", "data"]


@dataclass
class App:
    name: str
    command: str
    id: str = ""

    def to_dict(self) -> dict:
        return {"name": self.name, "command": self.command, "id": self.id or self.name.lower()}


@dataclass
class Profile:
    name: str
    title: str = ""
    description: str = ""
    icon: str = ""
    extends: str | None = None
    packages: list[str] = field(default_factory=list)
    setup: list[str] = field(default_factory=list)
    files: dict[str, str] = field(default_factory=dict)
    env: dict[str, str] = field(default_factory=dict)
    apps: list[App] = field(default_factory=list)
    autostart: list[str] = field(default_factory=list)
    memory: str = ""
    shm: str = ""
    cpus: str = ""
    size: str = ""
    tips: str = ""
    builtin: bool = False
    path: Path | None = None
    _registry: dict | None = field(default=None, repr=False)

    # -- inheritance ---------------------------------------------------
    def parent(self) -> Profile | None:
        if not self.extends:
            return None
        reg = self._registry if self._registry is not None else load_all()
        if self.extends not in reg:
            raise NotFound(f"profile {self.name!r} extends unknown profile {self.extends!r}")
        return reg[self.extends]

    def chain(self) -> list[Profile]:
        """Ancestors first, this profile last."""
        out: list[Profile] = []
        seen = set()
        p: Profile | None = self
        while p is not None:
            if p.name in seen:
                raise MinionError(f"profile inheritance cycle at {p.name!r}")
            seen.add(p.name)
            out.append(p)
            p = p.parent()
        return list(reversed(out))

    def merged(self, key: str):
        chain = self.chain()
        if key == "env":
            env: dict = {}
            for p in chain:
                env.update(p.env)
            return env
        if key == "apps":
            apps: dict[str, App] = {}
            for p in chain:
                for a in p.apps:
                    apps[(a.id or a.name).lower()] = a
            return list(apps.values())
        if key == "autostart":
            out: list[str] = []
            for p in chain:
                out.extend(p.autostart)
            return out
        for p in reversed(chain):  # scalar: nearest definition wins
            v = getattr(p, key)
            if v:
                return v
        return getattr(self, key)

    # -- images --------------------------------------------------------
    @property
    def image(self) -> str:
        if self.builtin:
            return f"{config.REGISTRY}/minion-{self.name}:{config.IMAGE_TAG}"
        return f"minion-custom-{self.name}:latest"

    def fingerprint(self) -> str:
        data = []
        for p in self.chain():
            data.append({"name": p.name, "packages": p.packages, "setup": p.setup,
                         "files": p.files, "builtin": p.builtin})
        if self.name == "base" or self.chain()[0].name == "base":
            dockerfile = BUILTIN_DIR.parent / "images" / "base.Dockerfile"
            try:
                data.append(dockerfile.read_text())
            except OSError:
                pass
        return hashlib.sha256(json.dumps(data, sort_keys=True).encode()).hexdigest()[:16]

    def dockerfile(self, parent_image: str) -> str:
        lines = [
            "# Generated by Minion from the profile "
            f"{self.name!r}{' (' + str(self.path) + ')' if self.path else ''}",
            f"FROM {parent_image}",
            "USER root",
        ]
        if self.packages:
            pkgs = " \\\n      ".join(sorted(set(self.packages)))
            lines.append(
                "RUN apt-get update \\\n"
                " && DEBIAN_FRONTEND=noninteractive apt-get install -y --no-install-recommends \\\n"
                f"      {pkgs} \\\n"
                " && apt-get clean && rm -rf /var/lib/apt/lists/*"
            )
        if self.files:
            lines.append("COPY files/ /")
        if self.setup:
            lines.append("RUN " + " \\\n && ".join(f"( {c} )" for c in self.setup))
        lines.append(f'LABEL dev.minion.profile="{self.name}" dev.minion.fingerprint="{self.fingerprint()}"')
        lines.append("USER agent")
        return "\n".join(lines) + "\n"

    def summary(self) -> dict:
        return {
            "name": self.name,
            "title": self.title or self.name.title(),
            "description": self.description,
            "icon": self.icon,
            "extends": self.extends,
            "apps": [a.name for a in self.merged("apps")],
            "image": self.image,
            "builtin": self.builtin,
            "memory": self.merged("memory"),
        }


def _parse(path: Path, builtin: bool) -> Profile:
    try:
        data = tomllib.loads(path.read_text(encoding="utf-8"))
    except (OSError, tomllib.TOMLDecodeError) as e:
        raise MinionError(f"invalid profile {path}: {e}") from e
    name = str(data.get("name") or path.stem)
    if not NAME_RE.match(name):
        raise MinionError(f"invalid profile name {name!r} in {path} (use a-z, 0-9, - and _)")
    apps = []
    for a in data.get("apps", []):
        if not isinstance(a, dict) or not a.get("name") or not a.get("command"):
            raise MinionError(f"{path}: every app needs a name and a command")
        apps.append(App(str(a["name"]), str(a["command"]), str(a.get("id", ""))))
    known = {"name", "title", "description", "icon", "extends", "packages", "setup", "files", "env",
             "apps", "autostart", "memory", "shm", "cpus", "size", "tips"}
    unknown = set(data) - known
    if unknown:
        raise MinionError(f"{path}: unknown keys {sorted(unknown)}")
    extends = data.get("extends")
    if extends is None and name != "base":
        extends = "base"
    return Profile(
        name=name,
        title=str(data.get("title", "")),
        description=str(data.get("description", "")),
        icon=str(data.get("icon", "")),
        extends=extends or None,
        packages=[str(p) for p in data.get("packages", [])],
        setup=[str(s) for s in data.get("setup", [])],
        files={str(k): str(v) for k, v in data.get("files", {}).items()},
        env={str(k): str(v) for k, v in data.get("env", {}).items()},
        apps=apps,
        autostart=[str(s) for s in data.get("autostart", [])],
        memory=str(data.get("memory", "")),
        shm=str(data.get("shm", "")),
        cpus=str(data.get("cpus", "")),
        size=str(data.get("size", "")),
        tips=str(data.get("tips", "")).strip(),
        builtin=builtin,
        path=path,
    )


def load_all() -> dict[str, Profile]:
    reg: dict[str, Profile] = {}
    for path in sorted(BUILTIN_DIR.glob("*.toml")):
        p = _parse(path, builtin=True)
        reg[p.name] = p
    udir = config.user_profiles_dir()
    if udir.is_dir():
        for path in sorted(udir.glob("*.toml")):
            p = _parse(path, builtin=False)
            if p.name == "base":
                raise MinionError(f"{path}: the base profile cannot be overridden")
            reg[p.name] = p
    for p in reg.values():
        p._registry = reg
    return reg


def get(name: str) -> Profile:
    reg = load_all()
    if name not in reg:
        raise NotFound(f"unknown profile {name!r}. Available: {', '.join(names(reg))}")
    return reg[name]


def names(reg: dict[str, Profile] | None = None) -> list[str]:
    reg = reg if reg is not None else load_all()
    order = {n: i for i, n in enumerate(BUILTIN_ORDER)}
    return sorted(reg, key=lambda n: (order.get(n, 100), n))
